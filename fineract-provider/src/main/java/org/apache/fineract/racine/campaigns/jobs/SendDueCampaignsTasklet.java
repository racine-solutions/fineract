package org.apache.fineract.racine.campaigns.jobs;

import lombok.RequiredArgsConstructor;
import org.apache.fineract.racine.campaigns.service.CampaignDispatcher;
import org.springframework.batch.core.StepContribution;
import org.springframework.batch.core.scope.context.ChunkContext;
import org.springframework.batch.core.step.tasklet.Tasklet;
import org.springframework.batch.repeat.RepeatStatus;

@RequiredArgsConstructor
public class SendDueCampaignsTasklet implements Tasklet {

    private final CampaignDispatcher dispatcher;

    @Override
    public RepeatStatus execute(final StepContribution contribution, final ChunkContext chunkContext) {
        dispatcher.runDueCampaigns();
        return RepeatStatus.FINISHED;
    }
}
